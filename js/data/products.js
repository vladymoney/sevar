/* ordering rules: wholesale only, the smallest order for any item is 1 bag (чувал) */
SEVAR.ORDER = { unit: 'чувал', units: 'чувала', min: 1, max: 9999 };
SEVAR.sku = (p, s) => p.slug + '|' + s.label;
SEVAR.orderable = (s) => s.bag > 0 && s.price > 0;
SEVAR.bagPrice = (s) => Math.round(s.bag * s.price * 100) / 100; /* gross (с ДДС) price of one bag */
SEVAR.eur = (n) => (Math.round(n * 100) / 100).toLocaleString('bg-BG', { minimumFractionDigits: 2, maximumFractionDigits: 2 }) + ' €';

SEVAR.productBySlug =(slug) => SEVAR.products.find(p => p.slug === slug);

